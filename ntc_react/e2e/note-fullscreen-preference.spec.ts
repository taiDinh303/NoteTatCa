import { test, expect } from "@playwright/test";
test("desktop fullscreen preference persists and stays hidden on mobile", async ({ page, request }) => {
  await request.post("http://127.0.0.1:5199/__fixture/reset");
  await page.setViewportSize({width:1440,height:900});
  await page.goto("/login");
  await page.getByLabel("Email address",{exact:true}).fill("a@example.test");
  await page.getByLabel("Password",{exact:true}).fill("Synthetic-password-123!");
  await page.getByRole("button",{name:"Sign in",exact:true}).click();
  await expect(page.locator(".note-card").first()).toBeVisible();
  await page.goto("/settings/appearance");
  const toggle=page.getByRole("switch",{name:"Always open notes in full screen",exact:true});
  await expect(toggle).not.toBeChecked();await toggle.click();await expect(toggle).toBeChecked();
  await page.reload();await expect(toggle).toBeChecked();
  await page.setViewportSize({width:393,height:852});await expect(toggle).toHaveCount(0);
  await page.setViewportSize({width:1440,height:900});await expect(toggle).toBeChecked();
  await page.goto("/notes");
  await page.locator(".note-open").first().click();
  const view=page.getByRole("dialog",{name:"View note",exact:true});
  await expect(view).toHaveClass(/fullscreen/);
  await view.getByRole("button",{name:"Edit",exact:true}).click();
  const edit=page.getByRole("dialog",{name:"Edit note",exact:true});
  await expect(edit).toHaveClass(/fullscreen/);
  await edit.getByRole("button",{name:"Close",exact:true}).click();
  await page.getByRole("button",{name:"Take a note",exact:true}).click();
  const dialog=page.getByRole("dialog",{name:"New note",exact:true});
  await expect(dialog).toHaveClass(/fullscreen/);
  await dialog.getByRole("button",{name:"Exit full screen",exact:true}).click();
  await expect(dialog).not.toHaveClass(/fullscreen/);
  await dialog.getByRole("button",{name:"Close",exact:true}).click();
  await page.getByRole("button",{name:"Take a note",exact:true}).click();await expect(dialog).toHaveClass(/fullscreen/);
  await dialog.getByRole("button",{name:"Close",exact:true}).click();
  await page.goto("/settings/appearance");await toggle.click();await expect(toggle).not.toBeChecked();
  await page.goto("/notes");await page.getByRole("button",{name:"Take a note",exact:true}).click();await expect(dialog).not.toHaveClass(/fullscreen/);
});
