import { expect, test } from "@playwright/test";

for (const width of [320, 393, 1440]) {
  test(`emoji picker inserts at saved content selection, undo and offline reload ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 900 });
    await page.goto("/guest");
    await page.getByRole("button", { name: "Take a note", exact: true }).click();
    let dialog = page.getByRole("dialog", { name: "New note", exact: true });
    await dialog.getByLabel("Note title", { exact: true }).fill("Emoji insertion");
    let content = dialog.getByRole("textbox", { name: "Note content", exact: true });
    await content.fill("alpha beta");
    await content.press("Control+End");
    await content.press("Control+Shift+ArrowLeft");
    await content.press("Control+b");
    await dialog.getByRole("button", { name: "Insert emoji or symbol", exact: true }).click();
    let picker = page.getByRole("dialog", { name: "Emoji and symbols", exact: true });
    await picker.getByLabel("Search emoji or symbols").fill("trái tim");
    await picker.getByRole("button").filter({ hasText: /^❤️$/ }).click();

    await expect(content).toHaveText("alpha ❤️");
    await expect(content.locator("strong")).toHaveText("❤️");
    await expect(picker).toBeVisible();
    await page.keyboard.press("Escape");
    await expect(picker).toBeHidden();
    await expect(dialog).toBeVisible();
    await dialog.getByRole("button", { name: "Undo", exact: true }).click();
    await expect(content).toHaveText("alpha beta");
    await dialog.getByRole("button", { name: "Redo", exact: true }).click();
    await expect(content).toHaveText("alpha ❤️");
    await content.press("Control+End");
    await dialog.getByRole("button", { name: "Insert emoji or symbol", exact: true }).click();
    picker = page.getByRole("dialog", { name: "Emoji and symbols", exact: true });
    await expect(picker.getByRole("region", { name: "Recently used" })).toContainText("❤️");
    await picker.getByLabel("Search emoji or symbols").fill("rocket");
    await picker.getByRole("button").filter({ hasText: /^🚀$/ }).click();
    await picker.getByLabel("Search emoji or symbols").fill("party popper");
    await picker.getByRole("button").filter({ hasText: /^🎉$/ }).click();
    await expect(content).toHaveText("alpha ❤️🚀🎉");
    const bounds = (await picker.boundingBox())!;
    expect(bounds.x).toBeGreaterThanOrEqual(0);
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(width);
    expect(await picker.evaluate(el => el.scrollWidth - el.clientWidth)).toBeLessThanOrEqual(1);
    await page.screenshot({ path: info.outputPath(`emoji-picker-${width}.png`) });
    // Clicking a different footer tool dismisses this panel without closing the note.
    await dialog.getByRole("button", { name: "Note background color", exact: true }).click();
    await expect(picker).toBeHidden();
    await page.keyboard.press("Escape");
    await dialog.getByRole("button", { name: "View", exact: true }).click();
    dialog = page.getByRole("dialog", { name: "View note", exact: true });
    await expect(dialog.getByRole("button", { name: "Insert emoji or symbol" })).toHaveCount(0);
    await dialog.getByRole("button", { name: "Close", exact: true }).click();
    await page.reload();
    await page.getByRole("button", { name: "Open Emoji insertion", exact: true }).click();
    dialog = page.getByRole("dialog", { name: "View note", exact: true });
    await expect(dialog.getByRole("region", { name: "Note content", exact: true })).toHaveText("alpha ❤️🚀🎉");
    await dialog.getByRole("button", { name: "Edit", exact: true }).click();
    dialog = page.getByRole("dialog", { name: "Edit note", exact: true });
    content = dialog.getByRole("textbox", { name: "Note content", exact: true });
    await content.press("Control+End");
    await page.context().setOffline(true);
    await dialog.getByRole("button", { name: "Insert emoji or symbol", exact: true }).click();
    picker = page.getByRole("dialog", { name: "Emoji and symbols", exact: true });
    await picker.getByLabel("Search emoji or symbols").fill("check mark");
    await picker.getByRole("button").filter({ hasText: /^✓$/ }).click();
    await expect(content).toHaveText("alpha ❤️🚀🎉✓");
    await expect(picker).toBeVisible();
  });

  test(`symbols replace title selection and support repeated insertion and limits ${width}`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 });
    await page.goto("/guest");
    await page.getByRole("button", { name: "Take a note", exact: true }).click();
    const dialog = page.getByRole("dialog", { name: "New note", exact: true });
    const title = dialog.getByLabel("Note title", { exact: true });
    await title.fill("My plan");
    await title.press("End");
    await title.press("Control+Shift+ArrowLeft");
    await dialog.getByRole("button", { name: "Insert emoji or symbol", exact: true }).click();
    const picker = page.getByRole("dialog", { name: "Emoji and symbols", exact: true });
    await picker.getByLabel("Search emoji or symbols").fill("ngoi sao den");
    await picker.getByRole("button").filter({ hasText: /^★$/ }).click();
    await expect(title).toHaveValue("My ★");
    await picker.getByLabel("Search emoji or symbols").fill("dau tich dung");
    await picker.getByRole("button").filter({ hasText: /^✓$/ }).click();
    await expect(title).toHaveValue("My ★✓");
    await page.keyboard.press("Escape");
    await title.focus();
    await title.press("Control+z");
    await expect(title).toHaveValue("My ★");
    await title.press("Control+Shift+z");
    await expect(title).toHaveValue("My ★✓");
    await dialog.getByRole("textbox", { name: "Note content", exact: true }).fill("Keep this content");
    await title.fill("x".repeat(149));
    await title.press("End");
    await dialog.getByRole("button", { name: "Insert emoji or symbol", exact: true }).click();
    await picker.getByLabel("Search emoji or symbols").fill("rocket");
    await picker.getByRole("button").filter({ hasText: /^🚀$/ }).click();
    await expect(title).toHaveValue("x".repeat(149));
    await expect(picker).toBeVisible();
    await expect(page.getByText("Note title can contain up to 150 characters.", { exact: true })).toBeVisible();
    await page.keyboard.press("Escape");
    await title.fill("My ★✓");
    await dialog.getByRole("button", { name: "Close", exact: true }).click();
    await page.reload();
    await page.getByRole("button", { name: "Open My ★✓", exact: true }).click();
    const view = page.getByRole("dialog", { name: "View note", exact: true });
    await expect(view.locator(".note-heading-title")).toHaveText("My ★✓");
    await expect(view.getByRole("region", { name: "Note content", exact: true })).toHaveText("Keep this content");
  });
}

test("Vietnamese categories show every character with scrolling and keyboard insertion", async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem("ntc.language.v1", "vi"));
  await page.goto("/guest");
  await page.getByRole("button", { name: "Tạo ghi chú", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Ghi chú mới", exact: true });
  const title = dialog.getByLabel("Tiêu đề ghi chú", { exact: true });
  await title.fill("Bàn phím ");
  await title.press("End");
  await dialog.getByRole("button", { name: "Chèn emoji hoặc ký tự", exact: true }).click();
  const picker = page.getByRole("dialog", { name: "Emoji và ký tự", exact: true });
  const group = picker.getByLabel("Nhóm emoji", { exact: true });
  await expect(picker.locator(".emoji-symbol-grid button")).toHaveCount(4019);
  await expect(picker.getByRole("button", { name: "Xem thêm ký tự", exact: true })).toHaveCount(0);
  await picker.locator(".emoji-symbol-grid button").last().scrollIntoViewIfNeeded();
  expect(await picker.evaluate(el => el.querySelector(".note-tool-body")!.scrollTop)).toBeGreaterThan(0);
  await picker.getByLabel("Nhóm emoji", { exact: true }).scrollIntoViewIfNeeded();
  await group.selectOption({ label: "Con người và cơ thể" });
  await expect(picker.locator(".emoji-symbol-grid button")).toHaveCount(2418);
  await group.selectOption({ label: "Ký tự đặc biệt" });
  const search = picker.getByLabel("Tìm emoji hoặc ký tự", { exact: true });
  await search.fill("zzzz no match");
  await expect(picker.getByText("Không tìm thấy emoji hoặc ký tự.", { exact: true })).toBeVisible();
  await search.fill("mui ten phai");
  const arrow = picker.getByRole("button").filter({ hasText: /^→$/ });
  await arrow.focus();
  await arrow.press("Enter");
  await expect(title).toHaveValue("Bàn phím →");
  await expect(picker).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(dialog.getByRole("button", { name: "Chèn emoji hoặc ký tự", exact: true })).toBeFocused();
});
