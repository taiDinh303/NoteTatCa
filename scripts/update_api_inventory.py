"""Generate the API inventory from an exported Swagger document, without DB access."""
import argparse
import json
from pathlib import Path
from datetime import date

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('openapi', type=Path)
parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'docs' / 'api-inventory.md')
parser.add_argument('--date', default=date.today().isoformat(), help='Date of the verified OpenAPI export (YYYY-MM-DD).')
args = parser.parse_args()
document = json.loads(args.openapi.read_text(encoding='utf-8-sig'))

def schema_name(schema):
    if '$ref' in schema:
        return schema['$ref'].rsplit('/', 1)[-1]
    if schema.get('type') == 'array':
        return schema_name(schema.get('items', {})) + '[]'
    return schema.get('type', 'unspecified')

groups = {'V1 — React': [], 'Legacy — Razor adapters': []}
for path, methods in sorted(document['paths'].items()):
    for method, operation in methods.items():
        if not path.startswith('/api/'):
            continue
        if method not in ('get', 'post', 'put', 'patch', 'delete'):
            continue
        body = operation.get('requestBody', {}).get('content', {})
        request = schema_name(next(iter(body.values())).get('schema', {})) if body else '—'
        responses = []
        for status, response in operation.get('responses', {}).items():
            if not status.startswith('2'):
                continue
            content = response.get('content', {})
            name = schema_name(next(iter(content.values())).get('schema', {})) if content else 'envelope; see contract'
            responses.append(f'{status}: {name}')
        query = ', '.join(f"{p['name']} ({p['in']})" for p in operation.get('parameters', []) if p['in'] != 'path') or '—'
        access = operation.get('x-ntc-access', 'authenticated; server ownership rules apply')
        row = f'| {method.upper()} `{path}` | {access} | {request} | {query} | {"; ".join(responses)} |'
        groups['V1 — React' if path.startswith('/api/v1/') else 'Legacy — Razor adapters'].append(row)

count = sum(map(len, groups.values()))
lines = ['# NoteTatCa — API inventory', '', f'> CURRENT from exported OpenAPI, {args.date}. Generated by scripts/update_api_inventory.py.', '',
         f'{count} controller operations. Health probes `/health/live` and `/health/ready` are public and listed separately in the [API contract](15-api-contract.md).', '',
         'Access metadata describes HTTP authorization; ownership and self-account checks also run inside services. A role never grants another user\'s note content. Each operation declares its success schema and shared error envelopes in OpenAPI. Common errors and compatibility limits are in the [contract](15-api-contract.md).', '']
for title, rows in groups.items():
    lines += [f'## {title}', '', '| Method / path | Access | JSON body schema | Query / headers | Success schema |', '| --- | --- | --- | --- | --- |'] + rows + ['']
args.output.parent.mkdir(parents=True, exist_ok=True)
args.output.write_text('\n'.join(lines), encoding='utf-8')
print(f'{count} operations -> {args.output}')
